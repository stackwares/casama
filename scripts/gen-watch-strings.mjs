#!/usr/bin/env node
// The watch apps' words (D-410, docs/WATCH-PLAN.md §6.9): every key in client/lib/l10n/app_en.arb
// that starts with `watch` (but not `watchPhone`, which is the phone's own Settings → Watch) is
// written into the Apple Watch app as Swift and into the Wear OS app as Android string resources,
// so the two watches and the phone can't drift apart.
//
//   node scripts/gen-watch-strings.mjs          write both files
//   node scripts/gen-watch-strings.mjs --check  fail when either is out of date
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const arbPath = join(root, "client/lib/l10n/app_en.arb");
const swiftPath = join(root, "client/ios/Shared/WatchStrings.swift");
const xmlPath = join(root, "client/wear/app/src/main/res/values/watch_strings.xml");

const SWIFT_KEYWORDS = new Set([
  "as",
  "break",
  "case",
  "catch",
  "class",
  "continue",
  "default",
  "defer",
  "do",
  "else",
  "enum",
  "extension",
  "fallthrough",
  "false",
  "for",
  "func",
  "guard",
  "if",
  "import",
  "in",
  "init",
  "inout",
  "internal",
  "is",
  "let",
  "nil",
  "operator",
  "private",
  "protocol",
  "public",
  "repeat",
  "return",
  "self",
  "static",
  "struct",
  "subscript",
  "super",
  "switch",
  "throw",
  "throws",
  "true",
  "try",
  "typealias",
  "var",
  "where",
  "while",
]);

/** The watch's keys, in the arb's order: [{ key, text, description, placeholders }]. */
export function watchStrings(arb) {
  const out = [];
  for (const [key, text] of Object.entries(arb)) {
    if (key.startsWith("@") || !key.startsWith("watch") || key.startsWith("watchPhone")) continue;
    if (!/^watch[A-Z]/.test(key)) continue;
    const meta = arb[`@${key}`] ?? {};
    const placeholders = [...String(text).matchAll(/\{(\w+)\}/g)].map((m) => m[1]);
    out.push({ key, text: String(text), description: meta.description ?? "", placeholders });
  }
  return out;
}

const swiftName = (key) => {
  const rest = key.slice("watch".length);
  const name = rest.charAt(0).toLowerCase() + rest.slice(1);
  return SWIFT_KEYWORDS.has(name) ? `\`${name}\`` : name;
};
const snake = (key) =>
  key
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/([A-Z])([A-Z][a-z])/g, "$1_$2")
    .toLowerCase();
const swiftLiteral = (s) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n");

export function renderSwift(items) {
  const lines = [
    "// Generated by scripts/gen-watch-strings.mjs from client/lib/l10n/app_en.arb. Don't edit.",
    "// The watch apps' words (D-410): change them in the arb and run the script.",
    "import Foundation",
    "",
    "enum WatchL10n {",
  ];
  for (const { key, text, description, placeholders } of items) {
    if (description) lines.push(`  /// ${description.replace(/\n/g, " ")}`);
    const name = swiftName(key);
    if (!placeholders.length) {
      lines.push(`  static let ${name} = "${swiftLiteral(text)}"`);
      continue;
    }
    const unique = [...new Set(placeholders)];
    const params = unique.map((p, i) => `${i === 0 ? "_ " : ""}${p}: String`).join(", ");
    let body = swiftLiteral(text);
    for (const p of unique) body = body.split(`{${p}}`).join(`\\(${p})`);
    lines.push(`  static func ${name}(${params}) -> String { "${body}" }`);
  }
  lines.push("}", "");
  return lines.join("\n");
}

const xmlText = (s) =>
  s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/\\/g, "\\\\")
    .replace(/'/g, "\\'")
    .replace(/"/g, '\\"')
    .replace(/@/g, "\\@")
    .replace(/\?/g, "\\?")
    .replace(/\n/g, "\\n");

export function renderXml(items) {
  const lines = [
    '<?xml version="1.0" encoding="utf-8"?>',
    "<!-- Generated by scripts/gen-watch-strings.mjs from client/lib/l10n/app_en.arb. Don't edit. -->",
    "<!-- The watch apps' words (D-410): change them in the arb and run the script. -->",
    "<resources>",
  ];
  for (const { key, text, placeholders } of items) {
    const unique = [...new Set(placeholders)];
    let body = xmlText(text).replace(/%/g, "%%");
    unique.forEach((p, i) => {
      body = body.split(`{${p}}`).join(`%${i + 1}$s`);
    });
    const formatted = unique.length ? "" : ' formatted="false"';
    lines.push(
      `    <string name="${snake(key)}"${formatted}>${unique.length ? body : xmlText(text)}</string>`,
    );
  }
  lines.push("</resources>", "");
  return lines.join("\n");
}

function main() {
  const check = process.argv.includes("--check");
  const items = watchStrings(JSON.parse(readFileSync(arbPath, "utf8")));
  const files = [
    [swiftPath, renderSwift(items)],
    [xmlPath, renderXml(items)],
  ];
  let stale = 0;
  for (const [path, text] of files) {
    let current = null;
    try {
      current = readFileSync(path, "utf8");
    } catch {}
    if (current === text) continue;
    if (check) {
      console.error(
        `out of date: ${path.slice(root.length + 1)} (run node scripts/gen-watch-strings.mjs)`,
      );
      stale += 1;
    } else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, text);
      console.log(`wrote ${path.slice(root.length + 1)} (${items.length} strings)`);
    }
  }
  if (stale) process.exit(1);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
