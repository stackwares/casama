/**
 * Regenerates src/generated/schema.ts from the SQL migrations (the source of truth):
 * starts a throwaway database, applies migrations, runs drizzle-kit pull.
 */
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { startTestDatabase } from "../src/testing.ts";

const pkg = fileURLToPath(new URL("..", import.meta.url));
const out = `${pkg}src/generated`;
const db = await startTestDatabase();
try {
  rmSync(out, { recursive: true, force: true });
  execFileSync(
    "npx",
    [
      "drizzle-kit",
      "pull",
      "--dialect=postgresql",
      `--url=${db.url}`,
      `--out=${out}`,
      "--schemaFilters=public",
    ],
    {
      cwd: pkg,
      stdio: "inherit",
    },
  );
  for (const f of ["schema.ts", "relations.ts"]) {
    const p = `${out}/${f}`;
    if (!existsSync(p)) continue;
    let src = readFileSync(p, "utf8");
    if (f === "schema.ts") {
      // auth.users lives outside the public schema; declare the columns we reference, before first use.
      src = src.replace(/^(import [^\n]*from "drizzle-orm\/pg-core")/m, (m) =>
        m.replace("pgTable,", "pgTable, pgSchema,"),
      );
      src = src.replace(
        /^(import \{ sql \} from "drizzle-orm")$/m,
        `$1\n\nexport const authSchema = pgSchema("auth");\nexport const usersInAuth = authSchema.table("users", {\n\tid: uuid().primaryKey().notNull(),\n\temail: text(),\n});\nconst users = usersInAuth;`,
      );
      // pgvector columns
      src = src.replace(
        /\t\/\/ TODO: failed to parse database type '(?:extensions\.)?vector\((\d+)\)'\n(\t\w+): unknown\("(\w+)"\)/g,
        '$2: vector("$3", { dimensions: $1 })',
      );
      // generated tsvector columns (read-only from the app)
      src = src.replace(
        /\t\/\/ TODO: failed to parse database type 'tsvector'\n(\t\w+): unknown\("(\w+)"\)/g,
        '$1: tsvector("$2")',
      );
      if (src.includes('vector("'))
        src = src.replace("pgTable, pgSchema,", "pgTable, pgSchema, vector, customType,");
      if (src.includes('tsvector("'))
        src = src.replace(
          /^(export const authSchema)/m,
          'const tsvector = customType<{ data: string }>({ dataType: () => "tsvector" });\n\n$1',
        );
      // Foreign keys that make a type cycle between two tables (conversations ↔ messages,
      // projects ↔ conversations). The app never needs their metadata; the database keeps them.
      for (const name of [
        "conversations_head_message_id_fkey",
        "projects_conversation_id_fkey",
        "runs_trigger_message_id_fkey",
      ]) {
        src = src.replace(
          new RegExp(
            `\\tforeignKey\\(\\{\\n(?:\\t\\t\\t[^\\n]*\\n){2}\\t\\t\\tname: "${name}"\\n\\t\\t\\}\\)[^\\n]*\\n`,
          ),
          "",
        );
      }
      // drizzle-kit renders empty-string defaults as .default(')
      src = src.replaceAll(".default(')", '.default("")');
      // citext columns are compared case-insensitively by Postgres; text is the right TS type.
      src = src
        .replace(/\t\/\/ TODO: failed to parse database type 'citext'\n/g, "")
        .replace(/unknown\("(\w+)"\)/g, 'text("$1")');
    }
    if (f === "relations.ts") src = src.replace(/from "\.\/schema"/, 'from "./schema.ts"');
    writeFileSync(
      p,
      `// GENERATED by packages/db/scripts/pull-schema.ts from supabase/migrations. DO NOT EDIT.\n// biome-ignore-all lint: generated\n${src}`,
    );
  }
  rmSync(`${out}/meta`, { recursive: true, force: true });
  for (const f of readdirSync(out)) if (f.endsWith(".sql")) rmSync(`${out}/${f}`, { force: true });
} finally {
  await db.stop();
}
