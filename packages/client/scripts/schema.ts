/**
 * Generates src/generated/schema.ts from the API's OpenAPI document with openapi-typescript.
 *
 * openapi-typescript builds its output with the TypeScript compiler API, which TypeScript 7 (the
 * native compiler this repo uses) no longer ships. So the generator gets TypeScript 5 under the
 * alias `typescript-api`, and a resolve hook points its `import "typescript"` there.
 */
import { readFileSync } from "node:fs";
import { registerHooks } from "node:module";
import { fileURLToPath } from "node:url";

export const SPEC = fileURLToPath(new URL("../../contracts/openapi.json", import.meta.url));
export const OUT = fileURLToPath(new URL("../src/generated/schema.ts", import.meta.url));

const HEADER = `/**
 * Generated by \`pnpm --filter @casama/client gen\` from packages/contracts/openapi.json.
 * Do not edit by hand.
 */

`;

let hooked = false;

export async function generateSchema(spec = SPEC): Promise<string> {
  if (!hooked) {
    hooked = true;
    const here = import.meta.url;
    registerHooks({
      resolve(specifier, context, next) {
        if (specifier === "typescript")
          return next("typescript-api", { ...context, parentURL: here });
        return next(specifier, context);
      },
    });
  }
  const { default: openapiTS, astToString } = await import("openapi-typescript");
  return HEADER + astToString(await openapiTS(JSON.parse(readFileSync(spec, "utf8"))));
}
