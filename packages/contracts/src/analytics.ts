/** The product analytics catalog (ANALYTICS-PLAN §6): the one list of events and their properties. */
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export interface CatalogProperty {
  type: "string" | "number" | "boolean";
  values?: string[];
}

export interface CatalogEvent {
  name: string;
  by: Array<"client" | "server">;
  description: string;
  properties: Record<string, CatalogProperty>;
  funnels: string[];
  personless?: boolean;
  /**
   * Also sent to Google Analytics 4 as one of its recommended events (D-398), so its built-in reports
   * (acquisition, monetization, engagement) fill in: `params` are copied from the event's own properties,
   * `set` adds constants. PostHog never gets the twin.
   */
  ga4_twin?: Ga4Twin;
}

export interface Ga4Twin {
  name: string;
  params: string[];
  set?: Record<string, string | number>;
}

/** GA4's recommended event names a twin may use (https://support.google.com/analytics/answer/9267735). */
export const GA4_RECOMMENDED_EVENTS = [
  "sign_up",
  "login",
  "tutorial_begin",
  "tutorial_complete",
  "begin_checkout",
  "purchase",
  "refund",
  "share",
  "join_group",
  "generate_lead",
  "search",
  "select_content",
  "view_promotion",
  "view_item_list",
  "select_item",
] as const;

/** Catalog event name → its GA4 twin, for the server's GA4 sink. */
export function ga4Twins(c: AnalyticsCatalog = loadAnalyticsCatalog()): Record<string, Ga4Twin> {
  return Object.fromEntries(c.events.filter((e) => e.ga4_twin).map((e) => [e.name, e.ga4_twin!]));
}

export interface AnalyticsCatalog {
  version: number;
  forbidden_property_words: string[];
  super_properties: string[];
  events: CatalogEvent[];
}

export const catalogPath = fileURLToPath(new URL("../analytics/catalog.json", import.meta.url));

export function loadAnalyticsCatalog(): AnalyticsCatalog {
  return JSON.parse(readFileSync(catalogPath, "utf8")) as AnalyticsCatalog;
}

/** Client events → their property keys (without wildcard keys). */
export function clientEventProperties(
  c: AnalyticsCatalog = loadAnalyticsCatalog(),
): Record<string, string[]> {
  return Object.fromEntries(
    c.events
      .filter((e) => e.by.includes("client"))
      .map((e) => [e.name, Object.keys(e.properties ?? {}).filter((k) => !k.includes("*"))]),
  );
}

/** The server's copy of the twins (its image has no catalog.json): src/ga4-twins.generated.ts. */
export function ga4TwinsSource(c: AnalyticsCatalog = loadAnalyticsCatalog()): string {
  const twins = Object.fromEntries(
    c.events.filter((e) => e.by.includes("server") && e.ga4_twin).map((e) => [e.name, e.ga4_twin!]),
  );
  return `// GENERATED by packages/contracts/src/scripts/emit-analytics.ts from analytics/catalog.json. Do not edit.
/** Server events Google Analytics 4 also gets as one of its recommended events (D-398). */
export const GA4_TWINS: Record<string, { name: string; params: string[]; set?: Record<string, string | number> }> = ${JSON.stringify(twins, null, 2)};

/** Events the app may send and their properties: what the desktop GA4 relay accepts (D-399). */
export const ANALYTICS_CLIENT_EVENTS: Record<string, string[]> = ${JSON.stringify(clientEventProperties(c), null, 2)};

/** The app's twins too, so relayed events get theirs. */
export const GA4_CLIENT_TWINS: Record<string, { name: string; params: string[]; set?: Record<string, string | number> }> = ${JSON.stringify(Object.fromEntries(c.events.filter((e) => e.by.includes("client") && e.ga4_twin).map((e) => [e.name, e.ga4_twin!])), null, 2)};
`;
}

/** The Dart source for the app: the events it may send and the features `feature_used` accepts. */
export function dartCatalog(c: AnalyticsCatalog = loadAnalyticsCatalog()): string {
  const quote = (xs: string[]) => xs.map((x) => `  '${x}',`).join("\n");
  const clientEvents = c.events.filter((e) => e.by.includes("client")).map((e) => e.name);
  const features =
    c.events.find((e) => e.name === "feature_used")?.properties.feature?.values ?? [];
  const dartValue = (v: string | number) => (typeof v === "number" ? String(v) : `'${v}'`);
  const twins = c.events
    .filter((e) => e.by.includes("client") && e.ga4_twin)
    .map((e) => {
      const t = e.ga4_twin!;
      const params = t.params.map((p) => `'${p}'`).join(", ");
      const set = Object.entries(t.set ?? {})
        .map(([k, v]) => `'${k}': ${dartValue(v)}`)
        .join(", ");
      return `  '${e.name}': (name: '${t.name}', params: <String>[${params}], set: <String, Object>{${set}}),`;
    })
    .join("\n");
  return `// GENERATED by packages/contracts/src/scripts/emit-analytics.ts from analytics/catalog.json. Do not edit.
// Product events the app may send (ANALYTICS-PLAN §6); anything else is dropped before it leaves the device.
const analyticsClientEvents = <String>{
${quote(clientEvents)}
};

/// The closed list of \`feature_used\` features.
const analyticsFeatures = <String>{
${quote(features)}
};

/// Events Google Analytics 4 also gets as one of its recommended events (D-398): the twin's name, the
/// event properties it copies and constants it adds.
const analyticsGa4Twins = <String, ({String name, List<String> params, Map<String, Object> set})>{
${twins}
};
`;
}
