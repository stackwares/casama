/** The product analytics catalog (ANALYTICS-PLAN §6): the one list of events and their properties. */
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export interface CatalogProperty {
  type: "string" | "number" | "boolean";
  values?: string[];
}

export interface CatalogEvent {
  name: string;
  by: Array<"client" | "server">;
  description: string;
  properties: Record<string, CatalogProperty>;
  funnels: string[];
  personless?: boolean;
}

export interface AnalyticsCatalog {
  version: number;
  forbidden_property_words: string[];
  super_properties: string[];
  events: CatalogEvent[];
}

export const catalogPath = fileURLToPath(new URL("../analytics/catalog.json", import.meta.url));

export function loadAnalyticsCatalog(): AnalyticsCatalog {
  return JSON.parse(readFileSync(catalogPath, "utf8")) as AnalyticsCatalog;
}

/** The Dart source for the app: the events it may send and the features `feature_used` accepts. */
export function dartCatalog(c: AnalyticsCatalog = loadAnalyticsCatalog()): string {
  const quote = (xs: string[]) => xs.map((x) => `  '${x}',`).join("\n");
  const clientEvents = c.events.filter((e) => e.by.includes("client")).map((e) => e.name);
  const features =
    c.events.find((e) => e.name === "feature_used")?.properties.feature?.values ?? [];
  return `// GENERATED by packages/contracts/src/scripts/emit-analytics.ts from analytics/catalog.json. Do not edit.
// Product events the app may send (ANALYTICS-PLAN §6); anything else is dropped before it leaves the device.
const analyticsClientEvents = <String>{
${quote(clientEvents)}
};

/// The closed list of \`feature_used\` features.
const analyticsFeatures = <String>{
${quote(features)}
};
`;
}
